/* ============================================================================
 * src/drivers/keyboard.c  -  PS/2 keyboard, scancode set 1, IRQ-driven
 * ============================================================================ */

#include "kernel.h"
#include "keyboard.h"
#include "mouse.h"
#include "interrupts.h"

#define KB_DATA    0x60
#define KB_STATUS  0x64

static key_event_t queue[KB_QUEUE_SIZE];
static int q_head, q_tail, q_count;

static u8  mods;
static int shift_l, shift_r, ctrl_l, ctrl_r, alt_l, alt_r, super_l, super_r;
static int caps;
static int e0_prefix;
static int e1_skip;
static u32 key_events;
static u32 kb_bytes;

static const char map_normal[128] = {
    [0x01] = 27,  [0x02] = '1', [0x03] = '2', [0x04] = '3', [0x05] = '4',
    [0x06] = '5', [0x07] = '6', [0x08] = '7', [0x09] = '8', [0x0A] = '9',
    [0x0B] = '0', [0x0C] = '-', [0x0D] = '=', [0x0E] = '\b', [0x0F] = '\t',
    [0x10] = 'q', [0x11] = 'w', [0x12] = 'e', [0x13] = 'r', [0x14] = 't',
    [0x15] = 'y', [0x16] = 'u', [0x17] = 'i', [0x18] = 'o', [0x19] = 'p',
    [0x1A] = '[', [0x1B] = ']', [0x1C] = '\n',
    [0x1E] = 'a', [0x1F] = 's', [0x20] = 'd', [0x21] = 'f', [0x22] = 'g',
    [0x23] = 'h', [0x24] = 'j', [0x25] = 'k', [0x26] = 'l', [0x27] = ';',
    [0x28] = '\'', [0x29] = '`', [0x2B] = '\\',
    [0x2C] = 'z', [0x2D] = 'x', [0x2E] = 'c', [0x2F] = 'v', [0x30] = 'b',
    [0x31] = 'n', [0x32] = 'm', [0x33] = ',', [0x34] = '.', [0x35] = '/',
    [0x37] = '*', [0x39] = ' ',
    [0x4A] = '-', [0x4E] = '+',
};

static const char map_shift[128] = {
    [0x01] = 27,  [0x02] = '!', [0x03] = '@', [0x04] = '#', [0x05] = '$',
    [0x06] = '%', [0x07] = '^', [0x08] = '&', [0x09] = '*', [0x0A] = '(',
    [0x0B] = ')', [0x0C] = '_', [0x0D] = '+', [0x0E] = '\b', [0x0F] = '\t',
    [0x10] = 'Q', [0x11] = 'W', [0x12] = 'E', [0x13] = 'R', [0x14] = 'T',
    [0x15] = 'Y', [0x16] = 'U', [0x17] = 'I', [0x18] = 'O', [0x19] = 'P',
    [0x1A] = '{', [0x1B] = '}', [0x1C] = '\n',
    [0x1E] = 'A', [0x1F] = 'S', [0x20] = 'D', [0x21] = 'F', [0x22] = 'G',
    [0x23] = 'H', [0x24] = 'J', [0x25] = 'K', [0x26] = 'L', [0x27] = ':',
    [0x28] = '"', [0x29] = '~', [0x2B] = '|',
    [0x2C] = 'Z', [0x2D] = 'X', [0x2E] = 'C', [0x2F] = 'V', [0x30] = 'B',
    [0x31] = 'N', [0x32] = 'M', [0x33] = '<', [0x34] = '>', [0x35] = '?',
    [0x37] = '*', [0x39] = ' ',
    [0x4A] = '-', [0x4E] = '+',
};

static void update_mods(void)
{
    mods = 0;
    if (shift_l || shift_r) mods |= MOD_SHIFT;
    if (ctrl_l || ctrl_r)   mods |= MOD_CTRL;
    if (alt_l || alt_r)     mods |= MOD_ALT;
    if (super_l || super_r) mods |= MOD_SUPER;
    if (caps)               mods |= MOD_CAPS;
}

static void push_key(u8 ch, u8 key)
{
    if (ch >= 'a' && ch <= 'z' && (mods & MOD_CAPS)) ch = (u8)(ch - 32);
    else if (ch >= 'A' && ch <= 'Z' && (mods & MOD_CAPS)) ch = (u8)(ch + 32);

    key_event_t ev;
    ev.ch = ch;
    ev.key = key;
    ev.mods = mods;
    ev.pad = 0;

    if (q_count >= KB_QUEUE_SIZE) return;
    queue[q_tail] = ev;
    q_tail = (q_tail + 1) % KB_QUEUE_SIZE;
    q_count++;
    key_events++;
}

static void handle_extended(u8 sc)
{
    if (sc & 0x80) {
        u8 code = (u8)(sc & 0x7F);
        if (code == 0x1D) ctrl_r = 0;
        else if (code == 0x38) alt_r = 0;
        else if (code == 0x5B) super_l = 0;
        else if (code == 0x5C) super_r = 0;
        update_mods();
        return;
    }

    switch (sc) {
    case 0x1D: ctrl_r = 1; update_mods(); break;
    case 0x38: alt_r = 1; update_mods(); break;
    case 0x5B: super_l = 1; update_mods(); push_key(0, KEY_SUPER); break;
    case 0x5C: super_r = 1; update_mods(); push_key(0, KEY_SUPER); break;
    case 0x5D: push_key(0, KEY_MENU); break;
    case 0x4B: push_key(0, KEY_LEFT); break;
    case 0x4D: push_key(0, KEY_RIGHT); break;
    case 0x48: push_key(0, KEY_UP); break;
    case 0x50: push_key(0, KEY_DOWN); break;
    case 0x47: push_key(0, KEY_HOME); break;
    case 0x4F: push_key(0, KEY_END); break;
    case 0x53: push_key(0, KEY_DELETE); break;
    case 0x49: push_key(0, KEY_PAGEUP); break;
    case 0x51: push_key(0, KEY_PAGEDOWN); break;
    case 0x52: push_key(0, KEY_INSERT); break;
    case 0x1C: push_key('\n', KEY_ENTER); break;
    case 0x35: push_key('/', KEY_NONE); break;
    case 0x2A:
    case 0x36:
        /* Fake shift generated by PrintScreen; ignore. */
        break;
    default:
        break;
    }
}

void keyboard_handle_scancode(u8 sc)
{
    kb_bytes++;

    if (e1_skip > 0) {
        e1_skip--;
        return;
    }
    if (sc == 0xE1) {
        e1_skip = 5;
        return;
    }
    if (sc == 0xE0) {
        e0_prefix = 1;
        return;
    }
    if (e0_prefix) {
        e0_prefix = 0;
        handle_extended(sc);
        return;
    }

    /* Releases. */
    if (sc & 0x80) {
        switch (sc & 0x7F) {
        case 0x2A: shift_l = 0; break;
        case 0x36: shift_r = 0; break;
        case 0x1D: ctrl_l = 0; break;
        case 0x38: alt_l = 0; break;
        default: break;
        }
        update_mods();
        return;
    }

    switch (sc) {
    case 0x2A: shift_l = 1; update_mods(); return;
    case 0x36: shift_r = 1; update_mods(); return;
    case 0x1D: ctrl_l = 1; update_mods(); return;
    case 0x38: alt_l = 1; update_mods(); return;
    case 0x3A: caps = !caps; update_mods(); return;
    case 0x3B: push_key(0, KEY_F1); return;
    case 0x3C: push_key(0, KEY_F2); return;
    case 0x3D: push_key(0, KEY_F3); return;
    case 0x3E: push_key(0, KEY_F4); return;
    case 0x3F: push_key(0, KEY_F5); return;
    case 0x40: push_key(0, KEY_F6); return;
    case 0x41: push_key(0, KEY_F7); return;
    case 0x42: push_key(0, KEY_F8); return;
    case 0x43: push_key(0, KEY_F9); return;
    case 0x44: push_key(0, KEY_F10); return;
    case 0x57: push_key(0, KEY_F11); return;
    case 0x58: push_key(0, KEY_F12); return;
    case 0x47: push_key(0, KEY_HOME); return;
    case 0x48: push_key(0, KEY_UP); return;
    case 0x49: push_key(0, KEY_PAGEUP); return;
    case 0x4B: push_key(0, KEY_LEFT); return;
    case 0x4D: push_key(0, KEY_RIGHT); return;
    case 0x4F: push_key(0, KEY_END); return;
    case 0x50: push_key(0, KEY_DOWN); return;
    case 0x51: push_key(0, KEY_PAGEDOWN); return;
    case 0x52: push_key(0, KEY_INSERT); return;
    case 0x53: push_key(0, KEY_DELETE); return;
    default: break;
    }

    char c = (mods & MOD_SHIFT) ? map_shift[sc] : map_normal[sc];
    if (!c) return;

    u8 key = KEY_NONE;
    if (sc == 0x1C) key = KEY_ENTER;
    else if (sc == 0x0E) key = KEY_BACKSPACE;
    else if (sc == 0x0F) key = KEY_TAB;
    else if (sc == 0x01) key = KEY_ESC;

    push_key((u8)c, key);
}

int keyboard_poll(key_event_t *out)
{
    if (q_count <= 0) return 0;
    if (out) *out = queue[q_head];
    q_head = (q_head + 1) % KB_QUEUE_SIZE;
    q_count--;
    return 1;
}

u8 keyboard_modifiers(void) { return mods; }
int keyboard_key_count(void) { return q_count; }
u32 keyboard_irq_count(void) { return kb_bytes; }

void keyboard_poll_raw(void)
{
    int guard = 32;
    while ((port_inb(KB_STATUS) & 0x01) && guard-- > 0) {
        u8 status = port_inb(KB_STATUS);
        u8 data = port_inb(KB_DATA);
        if (status & 0x20) mouse_handle_byte(data);
        else keyboard_handle_scancode(data);
    }
}

void keyboard_init(void)
{
    q_head = q_tail = q_count = 0;
    shift_l = shift_r = ctrl_l = ctrl_r = 0;
    alt_l = alt_r = super_l = super_r = 0;
    caps = 0;
    e0_prefix = 0;
    e1_skip = 0;
    key_events = 0;
    kb_bytes = 0;
    update_mods();

    /* Flush any bytes left in the controller output buffer. */
    int guard = 64;
    while ((port_inb(KB_STATUS) & 0x01) && guard-- > 0)
        (void)port_inb(KB_DATA);
}
